const ATTRIBUTES_TO_TRANSLATE = ["aria-label", "title", "placeholder", "alt"];

function isAppLanguage(value: string | null): value is AppLanguage {
  return value === "ja" || value === "en" || value === "zh";
}

export function readAppLanguage(): AppLanguage {
  if (typeof window === "undefined") {
    return "ja";
  }
  try {
    const stored = window.localStorage.getItem(DISPLAY_LANGUAGE_STORAGE_KEY);
    return isAppLanguage(stored) ? stored : "ja";
  } catch {
    return "ja";
  }
}

function applyDocumentLanguage(language: AppLanguage): void {
  if (typeof document !== "undefined") {
    document.documentElement.lang = HTML_LANGUAGE[language];
  }
}

export function writeAppLanguage(language: AppLanguage): void {
  if (typeof window === "undefined") {
    return;
  }
  window.localStorage.setItem(DISPLAY_LANGUAGE_STORAGE_KEY, language);
  applyDocumentLanguage(language);
  window.dispatchEvent(new Event(LANGUAGE_CHANGE_EVENT));
}

function subscribeLanguage(callback: () => void): () => void {
  if (typeof window === "undefined") {
    return () => undefined;
  }
  window.addEventListener(LANGUAGE_CHANGE_EVENT, callback);
  window.addEventListener("storage", callback);
  return () => {
    window.removeEventListener(LANGUAGE_CHANGE_EVENT, callback);
    window.removeEventListener("storage", callback);
  };
}

export function useAppLanguage(): {
  language: AppLanguage;
  locale: string;
  setLanguage(language: AppLanguage): void;
  t(value: string): string;
} {
  const language = useContext(LanguageContext);
  return {
    language,
    locale: LOCALE[language],
    setLanguage: writeAppLanguage,
    t: useCallback((value: string) => translateText(value, language), [language]),
  };
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const language = useSyncExternalStore(
    subscribeLanguage,
    readAppLanguage,
    () => "ja" as AppLanguage,
  );
  useEffect(() => applyDocumentLanguage(language), [language]);
  return (
    <LanguageContext.Provider value={language}>
      {children}
    </LanguageContext.Provider>
  );
}

