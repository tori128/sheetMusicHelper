export function translateText(value: string, language: AppLanguage): string {
  if (language === "ja" || value.trim() === "") {
    return value;
  }
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const source = value.trim().replace(/\s+/g, " ");
  const translated = (language === "en" ? EN : ZH)[source]
    ?? translatePattern(source, language);
  return translated === undefined || translated === null
    ? value
    : `${leading}${translated}${trailing}`;
}

function localizeNode(node: ReactNode, language: AppLanguage): ReactNode {
  if (typeof node === "string") {
    return translateText(node, language);
  }
  if (!isValidElement(node)) {
    return node;
  }
  const element = node as ReactElement<Record<string, unknown>>;
  if (element.props["data-localize"] === "false") {
    return element;
  }
  const props: Record<string, unknown> = {};
  for (const attribute of ATTRIBUTES_TO_TRANSLATE) {
    const value = element.props[attribute];
    if (typeof value === "string") {
      props[attribute] = translateText(value, language);
    }
  }
  if (element.props.children !== undefined) {
    props.children = Children.map(element.props.children as ReactNode, (child) =>
      localizeNode(child, language),
    );
  }
  return cloneElement(element, props);
}

export function Localized({ children }: { children: ReactNode }) {
  const language = useContext(LanguageContext);
  if (language === "ja") {
    return <>{children}</>;
  }
  return <>{Children.map(children, (child) => localizeNode(child, language))}</>;
}
